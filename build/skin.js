/* =====================================================================
   App skins

   A skin is a set of CSS custom properties plus a few extras: the page-title
   icons, the wordmark in the app bar, the artwork that goes in the empty right
   half of the app bar, and the colours Android paints the status bar and the
   launcher icon in.  Everything a skin can change is declared here, so adding
   one later is a matter of writing an entry and dropping in the files - no
   other part of the app has to know about it.

   Two skins ship today: `classic`, the blue look the app has had since 1.0,
   and `gothic`, a black-and-silver skin.  The Gothic artwork is generated by
   build/skins/gothic/make.py into skin_gothic.js, which this file must be
   loaded after.
   ===================================================================== */

