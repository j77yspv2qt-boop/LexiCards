const DEFAULT_SKIN = 'classic';

/* the browser chrome classic uses, captured before any skin can replace it, so
   switching back to classic restores it exactly */
const DEFAULT_APP_ICON = (function () {
  const link = document.querySelector('link[rel="icon"]');
  return link ? (link.getAttribute('href') || '') : '';
})();
const DEFAULT_THEME_COLOR = (function () {
  const meta = document.querySelector('meta[name="theme-color"]');
  return (meta && meta.getAttribute('content')) || '#1565C0';
})();

function skinIds() { return Object.keys(SKINS); }

function getSkin(id) {
  return SKINS[id] || SKINS[DEFAULT_SKIN];
}

function currentSkin() {
  return getSkin((state.settings && state.settings.skin) || DEFAULT_SKIN);
}

/* The skin's tokens are published as ONE stylesheet rule keyed on the
   data-skin attribute, not as ~90 inline custom properties on <html>.

   Setting a custom property on the root invalidates every element that reads
   it, and engines disagree about how soon that reaches the screen: the parts
   of the app the user has not just interacted with can keep the previous
   skin's colours until something else forces a restyle.  Writing a rule is
   the ordinary cascade path, so a switch repaints completely and at once -
   and replacing the rule is also what clears the previous skin, because its
   values simply stop existing. */
function skinSheet() {
  let sheet = document.getElementById('skin-vars');
  if (!sheet) {
    sheet = document.createElement('style');
    sheet.id = 'skin-vars';
    (document.head || document.documentElement).appendChild(sheet);
  }
  return sheet;
}

function skinVarsCSS(skin) {
  const vars = skin.vars || {};
  const names = Object.keys(vars);
  if (!names.length) return '';          /* classic: the stylesheet IS the look */
  return ':root[data-skin="' + skin.id + '"]{' +
    names.map(v => v + ':' + vars[v]).join(';') + '}';
}

/* Apply a skin: the custom properties, the page icons and the wordmark.  Safe
   to call before the DOM is ready and repeatedly afterwards. */
function applySkin(id) {
  const skin = getSkin(id);
  const root = document.documentElement;

  /* 1. the tokens, as one rule that replaces the previous skin's */
  root.setAttribute('data-skin', skin.id);
  skinSheet().textContent = skinVarsCSS(skin);

  /* 2. the page-title and tab icons (falls back to the built-in set) */
  if (typeof paintPageIcons === 'function') paintPageIcons();

  /* 3. the wordmark and the app-bar artwork */
  const name = $('#brandName');
  if (name) {
    if (skin.wordmarkImage) {
      name.innerHTML = '<img class="brand__logo" src="' + escapeHTML(skin.wordmarkImage) +
        '" alt="' + escapeHTML(skin.wordmark || 'LexiCards') + '">';
    } else {
      name.textContent = skin.wordmark || 'LexiCards';
    }
  }
  const slot = $('#appbarSlot');
  if (slot) {
    slot.innerHTML = skin.appbarImage
      ? '<img class="appbar__slot-img" src="' + escapeHTML(skin.appbarImage) + '" alt="">'
      : '';
  }

  /* 4. the browser chrome that follows the skin.  The favicon is written for
     every skin, not only the ones that bring one: otherwise the last skin's
     icon would stay in the browser tab after switching back to classic. */
  const meta = document.querySelector('meta[name="theme-color"]');
  if (meta) meta.setAttribute('content', skin.themeColor || DEFAULT_THEME_COLOR);
  const link = document.querySelector('link[rel="icon"]');
  if (link) link.setAttribute('href', skin.appIcon || DEFAULT_APP_ICON);

  /* 5. and the Android wrapper, which paints the system bars and can swap the
     launcher icon for a skinned one.  Both calls happen whatever the skin is,
     because classic has to be able to take them back again. */
  if (NATIVE.isNative && NATIVE.api) {
    try {
      if (typeof NATIVE.api.setSystemBars === 'function') {
        NATIVE.api.setSystemBars(skin.androidStatus || skin.themeColor || '',
          skin.androidNav || '', !!skin.androidNavLight);
      } else if (typeof NATIVE.api.setThemeColor === 'function') {
        NATIVE.api.setThemeColor(skin.androidStatus || skin.themeColor);
      }
    } catch (e) { /* a host without these is still a working host */ }
    try {
      if (typeof NATIVE.api.setLauncherIcon === 'function') NATIVE.api.setLauncherIcon(skin.id);
    } catch (e) { /* ditto */ }
  }
}

function setSkin(id) {
  if (!SKINS[id]) return false;
  state.settings.skin = id;
  saveSettings();
  applySkin(id);
  syncSkinUI();
  return true;
}

/* the picker in the App info sheet */
function syncSkinUI() {
  const box = $('#skinPicker');
  if (!box) return;
  const active = currentSkin().id;
  $$('.skinopt', box).forEach(b => {
    const on = b.getAttribute('data-skin') === active;
    b.classList.toggle('is-active', on);
    b.setAttribute('aria-checked', on ? 'true' : 'false');
  });
}

function skinPickerHTML() {
  return skinIds().map(id => {
    const s = SKINS[id];
    return '<button type="button" class="skinopt" role="radio" aria-checked="false" data-skin="' +
      escapeHTML(id) + '" style="--skin-a:' + escapeHTML(s.swatch || s.themeColor || '#1565C0') + '">' +
      '<span class="skinopt__swatch" aria-hidden="true"></span>' +
      '<span class="skinopt__text"><b>' + escapeHTML(s.name) + '</b>' +
      (s.note ? '<i>' + escapeHTML(s.note) + '</i>' : '') + '</span></button>';
  }).join('');
}

function initSkins() {
  const box = $('#skinPicker');
  if (box) box.innerHTML = skinPickerHTML();
  if (box) box.addEventListener('click', e => {
    const btn = e.target.closest('.skinopt');
    if (!btn) return;
    const id = btn.getAttribute('data-skin');
    if (setSkin(id)) showToast('Skin: ' + SKINS[id].name, 'ok');
  });
  applySkin((state.settings && state.settings.skin) || DEFAULT_SKIN);
}
